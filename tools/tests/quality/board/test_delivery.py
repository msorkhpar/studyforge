def index(milestones: dict[str, list[str]], stated: int | None = None, banner: bool = True) -> str:
    """An index in the generator's shape: banner, stated total, one table per milestone."""
    total = sum(len(names) for names in milestones.values())
    text = (
        BANNER if banner else "# A hand-kept list\n\n"
    ) + f"**{stated or total} capabilities · x.**\n\n"
    for milestone, names in milestones.items():
        text += f"## {milestone} — {len(names)} capabilities\n\n"
        text += "| capability | what it is |\n|---|---|\n"
        for name in names:
            what = "⛔ RETIRED 2026-09-12 (was: a thing)" if name == "FND-02" else "a thing"
            text += f"| `{name}` | {what} | area | — |\n"
        text += "\n"
    return text


def task(row: str, owns: str) -> str:
    """One epic entry in the shape the epics write it."""
    declaration = "**Milestone** **M0** · **Depends on** — · **Team** solo"
    return f"### {row} — a row\n{declaration}\n**Owns** {owns}\n\n"


