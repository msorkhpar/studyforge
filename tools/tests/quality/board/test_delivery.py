def board(closes: str) -> str:
    """A board whose milestone table carries `closes`."""
    return (
        "# Board\n\n## Milestones\n\n| Milestone | State | Ref | Record |\n|---|---|---|---|\n"
        + closes
    )


def write(root: Path, files: dict[str, str], message: str) -> str:
    """Write `files`, commit them on the current branch, and return the new sha."""
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text, encoding="utf-8")
        assert git(root, "add", name).returncode == 0
    assert git(root, *AUTHOR, "commit", "-q", "-m", message).returncode == 0
    return git(root, "rev-parse", "HEAD").stdout.strip()


def merge(root: Path, branch: str, subject: str) -> str:
    """Cut `branch`, commit on it, absorb it `--no-ff` under `subject`, return the merge sha."""
    assert git(root, "checkout", "-q", "-b", branch).returncode == 0
    write(root, {f"{branch.replace('/', '-')}.txt": "x\n"}, f"work on {branch}")
    assert git(root, "checkout", "-q", RELEASE).returncode == 0
    assert git(root, *AUTHOR, "merge", "--no-ff", "-q", branch, "-m", subject).returncode == 0
    return git(root, "rev-parse", "HEAD").stdout.strip()


@pytest.fixture
def repository(tmp_path: Path) -> Path:
    """The two waves the module docstring tabulates, tagged `base`, `wave1` and `wave2`."""
    assert git_binary()
    root = tmp_path / "repo"
    root.mkdir()
    assert git(root, "init", "-q", "-b", RELEASE).returncode == 0
    plan = {INDEX: index(POPULATION), "docs/tasks/README.md": README, "workspace.json": WORKSPACE}
    plan["docs/tasks/BOARD.md"] = board("| **M0** — foundations | ⏳ OPEN | — | x |\n")
    write(root, {**plan, **EPICS}, "the plan")
    assert git(root, "tag", "base").returncode == 0
    merge(root, "feat/SF-01-address", "Merge feat/SF-01-address (SF-01): the address model")
    merge(root, "chore/po-round1", "Merge chore/po-round1 (PO round 1): SF-02 ruled ready")
    closed = merge(root, "feat/NS-01-service", "Merge feat/NS-01-service: a sibling stood up")
    row = f"| **M0** — foundations | ✅ CLOSED | `{closed[:7]}` | x |\n"
    write(root, {"docs/tasks/BOARD.md": board(row)}, "close M0")
    assert git(root, "tag", "wave1").returncode == 0
    merge(root, "fix/W9-tidy", "Merge fix/W9-tidy (W9 -- follows SF-02): tidies SF-01's prose")
    assert git(root, "tag", "wave2").returncode == 0
    return root


