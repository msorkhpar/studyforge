# Clause 2 — the population is the GENERATED index, at `until`.


def test_the_population_MOVES_with_the_index_at_until(repository: Path) -> None:
    """⭐ A row the generator adds is read at the ref it lands. Plant: a hand-kept list → RED."""
    grown = {**POPULATION, "M1": ["SF-03", "FND-02", "SF-10"]}
    write(repository, {INDEX: index(grown)}, "regenerate the index")
    before, after = read(repository, "base", "wave1"), read(repository, "base", "HEAD")
    assert len(before.population.milestone) == len(POPULATION["M0"] + POPULATION["M1"])
    assert set(after.population.milestone) - set(before.population.milestone) == {"SF-10"}
    assert before.population.retired == {"FND-02"}


