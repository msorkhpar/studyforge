"""The question bank: every question intake asks a course author, as data.

**What it does.** `BANK` lists each question with its group, tier, kind, tracks, the late
cost of leaving it open (`why`) and a concrete proposal (`default`). The checker and the
skill both read it, so what is asked and what is checked cannot drift apart.

**How you use it.**

    from studyforge.skills.intake.bank import BANK, by_id
    by_id()["practice.shape"].default

**Depends on.** `questions.Question` and `TRACKS`.
"""

from __future__ import annotations

from . import TRACKS
from .questions import Question

ALL = frozenset(TRACKS)


def _q(qid: str, tier: str, ask: str, why: str, default: str, *, kind: str = "text",
       tracks: frozenset[str] = ALL, choices: tuple[str, ...] = (),
       depends_on: tuple[str, tuple[object, ...]] | None = None) -> Question:
    return Question(id=qid, group=qid.split(".", 1)[0], ask=ask, why=why, default=default,
                    tracks=tracks, tier=tier, kind=kind, choices=choices,
                    depends_on=depends_on)


def _only(track: str) -> frozenset[str]:
    return frozenset({track})


